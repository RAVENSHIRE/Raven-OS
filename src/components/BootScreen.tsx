export default function BootScreen({ onComplete }: { onComplete: () => void }) {
  const [lines, setLines] = useState<string[]>([]);
  const asciiLines = useMemo(() => silverRavenAscii.split("\n"), []);
  const asciiStyle = useMemo<React.CSSProperties>(
    () => ({
      fontSize: "0.38rem",
      lineHeight: 1,
    }),
    [],
  );

  const bootSequence = [
    "RAVEN OS v1.0",
    "Initializing...",
    "Loading kernel... OK",
    "Mounting filesystem... OK",
    "Starting desktop...",
  ];

  useEffect(() => {
    let currentLine = 0;
    const interval = setInterval(() => {
      if (currentLine < bootSequence.length) {
        setLines((prev) => [...prev, bootSequence[currentLine]]);
        currentLine++;
      } else {
        clearInterval(interval);
        setTimeout(onComplete, 1000);
      }
    }, 600);

    return () => clearInterval(interval);
  }, [onComplete]);

  return (
    <div className="fixed inset-0 z-50 flex flex-col items-center justify-center overflow-hidden bg-black px-5 py-3 font-mono text-[#00FF00] selection:bg-transparent sm:px-8 sm:py-4">
      <pre className="whitespace-pre leading-none" style={asciiStyle}>
        {silverRavenAscii}
      </pre>

      {lines.map((line, i) => (
        <div key={i}>{line}</div>
      ))}
      {lines.length < bootSequence.length && <div className="animate-pulse">_</div>}
    </div>
  );
}
